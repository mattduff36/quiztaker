test('shared questions accept current and legacy decisions, strip kind and reject unexpected fields',()=>{
  for(const detected of ['session-dead','server-assessment','certification']) {
    const decision=decideGuidedFlow({detected},'read');
    assert.equal(decision.kind,'question');
    if(decision.kind!=='question')throw new Error('Expected a question');
    const question={question:decision.question,next:decision.next,targetId:'course',cdpTargetId:'live-course',
      sessionId:'session',url:'https://example.invalid/course'};
    assert.deepEqual(draftPatchSchema.parse({question}),{question});
    assert.deepEqual(draftPatchSchema.parse({question:{...decision,...question}}),{question});
    for(const extra of [{kind:'learn'},{unexpected:true},{capability:'scorm-complete'}]) {
      assert.equal(draftPatchSchema.safeParse({question:{...question,...extra}}).success,false);
    }
  }
  assert.deepEqual(draftPatchSchema.parse({question:null}),{question:null});
  assert.equal(draftPatchSchema.safeParse({unexpected:true}).success,false);
});

test('job admission rechecks bound workflow ownership after planning and on fallback requests',async()=>{
  const store=new MobileStore(),clientA=randomUUID(),clientB=randomUUID();
  const begin=(clientId:string)=>sharedOperations(store.userId,{helperId:store.helperId,clientId,workflowId:randomUUID(),action:'begin',sessionId:store.sessionId},store);
  const a=await begin(clientA);
  let bound={operations_workflow_id:a.workflowId,operations_client_id:clientA};
  const sql:SqlQuery=async<T>(text:string,values:unknown[]=[])=>{
    if(text.startsWith('select operations_workflow_id'))return values[1]===store.userId&&values[2]===store.helperId?[bound] as T[]:[];
    return store.query<T>(text,values);
  };
  await assertPlanWorkflow(sql,store.userId,store.helperId,'plan',{clientId:clientA,workflowId:a.workflowId!});
  store.draft!.workflow_until=new Date(Date.now()-1000).toISOString();
  const b=await begin(clientB);
  await assert.rejects(assertPlanWorkflow(sql,store.userId,store.helperId,'plan',{clientId:clientA,workflowId:a.workflowId!}),/Another device/);
  await assert.rejects(assertPlanWorkflow(sql,store.userId,store.helperId,'plan'),/ownership changed/);
  bound={operations_workflow_id:b.workflowId,operations_client_id:clientB};
  await assertPlanWorkflow(sql,store.userId,store.helperId,'plan',{clientId:clientB,workflowId:b.workflowId!});
  await assert.rejects(assertPlanWorkflow(sql,'other',store.helperId,'plan',{clientId:clientB,workflowId:b.workflowId!}),/not found/);
  store.draft!.workflow_until=new Date(Date.now()-1000).toISOString();
  await assert.rejects(assertPlanWorkflow(sql,store.userId,store.helperId,'plan',{clientId:clientB,workflowId:b.workflowId!}),/expired/);
});
test('relay ownership precedes cancellation; idle acknowledgement, one controller, expiry and at-most-once delivery',async()=>{
  const store=new MobileStore(),viewerKeys=await createRemoteKeys(),helperKeys=await createRemoteKeys();
  const context={helperId:store.helperId,sessionId:randomUUID(),clientId:randomUUID()};
  const view=(action:'open'|'poll'|'close'|'control'|'release'|'input'|'view-tab',extra={})=>remoteViewer(store.userId,{...context,action,...extra},store);
  await assert.rejects(remoteViewer('other',{...context,action:'control'},store),/not found/);
  assert.equal(store.pauses,0);
  await view('open',{publicKey:viewerKeys.publicKey});
  await assert.rejects(remoteViewer(store.userId,{...context,clientId:randomUUID(),action:'control'},store),/expired/);
  assert.equal(store.pauses,0);
  store.active=true;await view('control');assert.equal(store.paused,true);
  const key=await deriveRemoteKey(viewerKeys.privateKey,helperKeys.publicKey);
  const tabCommand=await sealRemote(key,context,'input',1,{type:'select-tab',targetId:'fixture'});
  await view('view-tab',{command:tabCommand});
  let exchange=await remoteHelper(store.userId,store.helperId,{idle:false,updates:[]},store);
  assert.equal(exchange.sessions[0]!.manual,false);assert.equal(exchange.manualReserved,true);
  assert.equal(exchange.sessions[0]!.command?.viewOnly,true);
  assert.deepEqual(exchange.sessions[0]!.command,{...tabCommand,viewOnly:true},'read-only capture tab selection remains available during automation');
  exchange=await remoteHelper(store.userId,store.helperId,{idle:true,updates:[]},store);
  assert.equal(exchange.sessions[0]!.manual,false,'DB active job still prevents control');
  store.active=false;
  exchange=await remoteHelper(store.userId,store.helperId,{idle:false,updates:[]},store);
  assert.equal(exchange.sessions[0]!.manual,false,'helper-local finishing work still prevents control');
  exchange=await remoteHelper(store.userId,store.helperId,{idle:true,updates:[]},store);
  assert.equal(exchange.sessions[0]!.manual,true);
  const other={...context,sessionId:randomUUID(),clientId:randomUUID(),publicKey:viewerKeys.publicKey};
  await remoteViewer(store.userId,{...other,action:'open'},store);
  await assert.rejects(remoteViewer(store.userId,{...other,action:'control'},store),/Another device/);
  const command=await sealRemote(key,context,'input',2,{type:'type',text:'private-fixture'});
  await view('input',{command});
  assert.equal(JSON.stringify([...store.remote.values()]).includes('private-fixture'),false);
  await view('input',{command});
  exchange=await remoteHelper(store.userId,store.helperId,{idle:true,updates:[]},store);
  assert.deepEqual(exchange.sessions.find(s=>s.sessionId===context.sessionId)!.command,command);
  exchange=await remoteHelper(store.userId,store.helperId,{idle:true,updates:[]},store);
  assert.equal(exchange.sessions.find(s=>s.sessionId===context.sessionId)!.command,null,'consumed command cannot be replay-delivered');
  await assert.rejects(view('input',{command:{...command,seq:0}}),/Invalid/);
  await view('release');assert.ok(store.helper.remote_lease_until,'release retains an admission barrier until local idle ack');
  await remoteHelper(store.userId,store.helperId,{idle:false,updates:[]},store);
  assert.ok(store.helper.remote_lease_until);
  await remoteHelper(store.userId,store.helperId,{idle:true,updates:[]},store);
  assert.equal(store.helper.remote_lease_until,null);
  store.helper.remote_lease_until=new Date(Date.now()-1).toISOString();
  assert.equal((await view('poll')).manual,false);
  store.remote.get(context.sessionId)!.expires_at=new Date(Date.now()-1).toISOString();
  await assert.rejects(view('poll'),/expired/);
  assert.equal((await view('close')).closed,true);
  assert.equal((await view('close')).closed,true,'disconnect cleanup is idempotent after expiry');
});
test('two client revisions preserve pending edits, ignore stale responses and serialize workflow starts',async()=>{
  const store=new MobileStore(),a=randomUUID(),b=randomUUID(),base={helperId:store.helperId};
  const call=(clientId:string,action:'read'|'edit'|'begin'|'renew'|'end'|'clear-guidance',extra={})=>sharedOperations(store.userId,{...base,clientId,action,...extra},store);
  const first=await call(a,'read'),replicaA=new SharedDraftReplica(),replicaB=new SharedDraftReplica();
  replicaA.receive(first);replicaB.receive(first);
  replicaA.edit({objective:'Read the material',selectedTarget:'course'});const editA=replicaA.request();
  const second=await call(a,'edit',{...editA});replicaA.receive(second,editA);
  replicaB.edit({answer:'Pending local reply'});
  replicaB.receive(second);assert.equal(replicaB.draft.answer,'Pending local reply');assert.equal(replicaB.draft.objective,'Read the material');
  const conflict=await call(b,'edit',{revision:first.revision,patch:{answer:'Pending local reply'}});
  assert.equal(conflict.conflict,true);
  const editB=replicaB.request();const third=await call(b,'edit',editB);replicaB.receive(third,editB);
  replicaA.receive(third);replicaA.receive(second);assert.equal(replicaA.draft.answer,'Pending local reply');
  assert.equal(replicaA.snapshot.revision,third.revision);
  await call(a,'edit',{revision:third.revision,patch:{guidance:'A newer hint'}});
  let hint=await call(b,'clear-guidance',{text:'Accepted older hint',sessionId:store.sessionId});
  assert.equal(hint.draft.guidance,'A newer hint','an accepted hint cannot erase a newer two-device draft');
  hint=await call(a,'clear-guidance',{text:'A newer hint',sessionId:store.sessionId});assert.equal(hint.draft.guidance,'');
  await assert.rejects(call(a,'clear-guidance',{text:'A newer hint',sessionId:randomUUID()}),/session changed/);
  replicaB.edit({guidance:'Accepted hint'});replicaB.forgetGuidance('Accepted hint');
  assert.equal(replicaB.pending.guidance,undefined);
  replicaB.edit({guidance:'New pending hint'});replicaB.forgetGuidance('Accepted hint');
  assert.equal(replicaB.pending.guidance,'New pending hint');
  const concurrent=new SharedDraftReplica();concurrent.receive(third);
  concurrent.edit({objective:'Acknowledged goal'});const sent=concurrent.request();
  concurrent.edit({answer:'Newer pending answer'});
  concurrent.receive({...third,revision:third.revision+1,draft:{objective:'Acknowledged goal'}},sent);
  assert.deepEqual(concurrent.pending,{answer:'Newer pending answer'},'acknowledged fields stop rebroadcasting even when another field was edited in flight');
  concurrent.receive({...third,revision:third.revision+2,draft:{objective:'Other device goal'}});
  assert.equal(concurrent.draft.objective,'Other device goal');assert.equal(concurrent.draft.answer,'Newer pending answer');
  const workflowA=randomUUID(),workflowB=randomUUID();
  const attempts=await Promise.allSettled([call(a,'begin',{workflowId:workflowA}),call(b,'begin',{workflowId:workflowB})]);
  assert.equal(attempts.filter(x=>x.status==='fulfilled').length,1);
  await assert.rejects(assertSharedWorkflow(store.query,store.userId,store.helperId,b,workflowB),/Another device/);
  await call(a,'end',{workflowId:workflowA});await call(b,'begin',{workflowId:workflowB});
  store.helper.remote_lease_until=new Date(Date.now()+15000).toISOString();
  await assert.rejects(call(b,'renew',{workflowId:workflowB}),/manual/);
  store.sessionId=randomUUID();store.helper.remote_lease_until=null;
  const reset=await call(a,'read');assert.deepEqual(reset.draft,{});assert.equal(reset.workflowId,null);
  replicaA.edit({objective:'Stale previous-session goal'});replicaA.receive(reset);
  assert.deepEqual(replicaA.pending,{},'pending edits cannot leak into another browser session');
  await assert.rejects(sharedOperations('wrong',{...base,clientId:a,action:'read'},store),/not found/);
});
test('durable request identity prevents repeated side effects even after unknown response/crash',async()=>{
  const store=new MobileStore(),request=randomUUID();let runs=0;
  const execute=()=>{runs++;return Promise.resolve(Response.json({jobId:'one-job'}));};
  const invoke=()=>idempotentOperation(store.userId,store.helperId,request,{action:'plan'},execute,store);
  const results=await Promise.all([invoke(),invoke()]);
  assert.equal(runs,1);assert.ok(results.some(r=>r.status===200));
  assert.deepEqual(await (await invoke()).json(),{jobId:'one-job'});
  await assert.rejects(idempotentOperation(store.userId,store.helperId,request,{action:'different'},execute,store),/reused/);
  const uncertain=randomUUID();
  await assert.rejects(idempotentOperation(store.userId,store.helperId,uncertain,{},async()=>{runs++;throw new Error('crash after effect');},store),/crash/);
  const repeated=await idempotentOperation(store.userId,store.helperId,uncertain,{},execute,store);
  assert.equal(repeated.status,409);assert.equal(runs,2);
});
